export function createDefaultSettings(type: ContentTypeId = "job"): DisplaySettings {
  const config = CONTENT_TYPES[type];
  const searchFields = config.searchFields.filter((f) => f.defaultOn).map((f) => f.id);
  return {
    contentType: type,
    listing: {
      showSearch: true,
      searchPlaceholder: searchPlaceholderFor(config, searchFields),
      searchFields,
      primaryFilters: defaultPrimaryFilters(),
      extraFilters: defaultExtraFilters(config),
      barButtonLabel: "ค้นหา",
      enableHomeBar: false,
      homeBarStyle: "dark",
      listingBarStyle: "card",
      showResultCount: true,
      columns: 3,
      pagination: "pagination",
      allowViewToggle: false,
      defaultView: "grid",
    },
    card: {
      layout: "top",
      showThumbnail: true,
      emptyImage: "placeholder",
      showTitle: true,
      showDescription: true,
      showCategory: true,
      showLocation: true,
      showPrice: true,
      showStatus: true,
      showCta: true,
      ctaStyle: "link",
      ctaLabel: config.ctaLabel,
      ctaIcon: { mode: "default" },
      categoryIcon: { mode: "default" },
      locationIcon: { mode: "default" },
      priceIcon: { mode: "default" },
      meta1: { ...config.metaDefaults[0] },
      meta2: { ...config.metaDefaults[1] },
    },
    detail: {
      showPrice: true,
      showLocation: true,
      showCategory: true,
      showStatus: true,
      showResponsibilities: type === "job",
      showQualifications: type === "job",
      showBenefits: type === "job" || type === "product",
      showBody: type !== "job",
      primaryAction: config.detailCta,
    },
    seo: {
      pageTitle: `${config.pageName} | Readyplanet`,
      slug: `/${type === "job" ? "career/open-positions" : type}`,
      metaDescription: config.heroSubtitle,
      indexable: true,
      published: true,
    },
    mobile: {
      hideHomeBar: false,
      hideExtraFilters: false,
      hideThumbnail: false,
      hideDescription: false,
      hideCategory: false,
      hideLocation: false,
      hidePrice: false,
      hideStatus: false,
      hideCta: false,
    },
  };
}

export function applyContentType(
  current: DisplaySettings,
  type: ContentTypeId,
): DisplaySettings {
  const next = createDefaultSettings(type);
  const config = CONTENT_TYPES[type];
  const primaryFilters = sanitizeFilterKeys(current.listing.primaryFilters, config);
  const extraFilters = sanitizeFilterKeys(current.listing.extraFilters, config).filter(
    (key) => !primaryFilters.includes(key),
  );
  const fallbackPrimary =
    primaryFilters.length > 0 ? primaryFilters : defaultPrimaryFilters();
  const fallbackExtra =
    extraFilters.length > 0
      ? extraFilters
      : defaultExtraFilters(config).filter((key) => !fallbackPrimary.includes(key));
  return {
    ...next,
    listing: {
      ...next.listing,
      showSearch: current.listing.showSearch,
      primaryFilters: fallbackPrimary,
      extraFilters: fallbackExtra,
      barButtonLabel: current.listing.barButtonLabel || next.listing.barButtonLabel,
      enableHomeBar: current.listing.enableHomeBar ?? next.listing.enableHomeBar,
      homeBarStyle: current.listing.homeBarStyle || next.listing.homeBarStyle,
      listingBarStyle:
        current.listing.listingBarStyle || next.listing.listingBarStyle,
      showResultCount: current.listing.showResultCount,
      columns: current.listing.columns,
      pagination: current.listing.pagination,
      allowViewToggle:
        current.listing.allowViewToggle ?? next.listing.allowViewToggle,
      defaultView: current.listing.defaultView || next.listing.defaultView,
    },
    card: {
      ...next.card,
      layout: current.card.layout,
      showThumbnail:
        current.card.layout === "none" ? false : current.card.showThumbnail,
      emptyImage: current.card.emptyImage,
      showTitle: current.card.showTitle,
      showDescription: current.card.showDescription,
      showCategory: current.card.showCategory,
      showLocation: current.card.showLocation,
      showPrice: current.card.showPrice,
      showStatus: current.card.showStatus,
      showCta: current.card.showCta,
      ctaStyle: current.card.ctaStyle || next.card.ctaStyle,
      ctaIcon: current.card.ctaIcon ?? next.card.ctaIcon,
      categoryIcon: current.card.categoryIcon ?? next.card.categoryIcon,
      locationIcon: current.card.locationIcon ?? next.card.locationIcon,
      priceIcon: current.card.priceIcon ?? next.card.priceIcon,
    },
    detail: {
      ...next.detail,
      showPrice: current.detail.showPrice,
      showLocation: current.detail.showLocation,
      showCategory: current.detail.showCategory,
      showStatus: current.detail.showStatus,
    },
    seo: {
      ...next.seo,
      indexable: current.seo.indexable,
      published: current.seo.published,
    },
    mobile: {
      ...next.mobile,
      ...(current.mobile ?? {}),
    },
  };
}

